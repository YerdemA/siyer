def iddialar(sahne_id: str, parcalar: list[int]) -> list[str]:
    bolum = next(BOLUM.glob(f"{sahne_id[:3]}-*.json"))
    b = json.loads(bolum.read_text(encoding="utf-8"))
    s = next(s for s in b["sahneler"] if s["id"] == sahne_id)
    cikti = []
    for p in parcalar:
        for i in s["anlatim"][p]["iddialar"]:
            if i not in cikti:
                cikti.append(i)
    return cikti


def kayit(bolum: str, r: dict) -> dict:
    ids = iddialar(r["sahne"], r["parca"])
    not_ = f"Dinamizm turu d1 ({r['oncelik']}). {r['gerekce']} Dayanak: {r['sahne']} parça {', '.join(map(str, r['parca']))}; {', '.join(ids)}."
    if r["ek_not"]:
        not_ += " " + r["ek_not"]
    k = {
        "id": r["id"], "tur": "d1", "dosya": r["id"] + ".webp", "katman": r["id"].split("-d-", 1)[1],
        "isleme": "opak", "sahneler": [r["sahne"]], "sahne": r["sahne"], "parca": r["parca"],
        "oncelik": r["oncelik"], "tip": r["tip"], "cekim": r["cekim"], "konu": r["konu"],
    }
    if r["kisiler"]:
        k["kisiler"] = r["kisiler"]
    if r["ekle"]:
        k["ekle"] = r["ekle"]
    k["isik"] = r["isik"]
    k["yasak"] = r["yasak"]
    k["not"] = not_
    return k


def main() -> None:
    toplam = 0
    for bolum, liste in KAYITLAR.items():
        yol = ISTEM / f"{bolum}.json"
        veri = json.loads(yol.read_text(encoding="utf-8"))
        idler = {r["id"] for r in liste}
        veri["istemler"] = [x for x in veri["istemler"] if x["id"] not in idler] + [kayit(bolum, r) for r in liste]
        yol.write_text(json.dumps(veri, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        toplam += len(liste)
        a = sum(r["oncelik"] == "A" for r in liste)
        print(f"{bolum}: {len(liste)} istem ({a} A, {len(liste) - a} B)")
    print(f"toplam {toplam}")


if __name__ == "__main__":
    main()
